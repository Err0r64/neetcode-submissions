class Solution {
public:
    // Assuming the list is sorted
    // nums=[1,2,3,3]
    /***

    */
    bool hasDuplicate(vector<int>& nums) {
        sort(nums.begin(), nums.end());
        for (int i = 1; i < nums.size(); i++) {
            if (nums[i] == nums[i - 1]) {
                return true;
            }
        }
        return false;
    }
};